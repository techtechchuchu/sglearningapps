// Builds the SQL that registers cropped hand-solution exams as 학교 기출 시험 and points each problem at its image.
//
//   node scripts/build-hand-solution-sql.cjs > supabase/data/<name>.sql
//
// Reads upload-staging/problem-solutions/<slug>/manifest.json (written by crop-hand-solutions.cjs).
// The images themselves must be uploaded to the private "problem-solutions" storage bucket under <slug>/NN.webp.
const fs = require("node:fs");
const path = require("node:path");

const EXAMS = {
  "2025-namok-g1-2-final": "남목고",
  "2025-seonggwang-girls-g1-2-final": "성광여고",
  "2025-sinseon-girls-g1-2-final": "신선여고",
  "2025-sinjeong-g1-2-final": "신정고",
  "2025-hogye-g1-2-final": "호계고",
  "2025-hwabong-g1-2-final": "화봉고",
};
const YEAR = 2025, SUBJECT = "공통수학2", EXAM_TYPE = "2학기 기말", SCOPE = "고1 2학기 기말", TITLE = "손풀이";
const root = path.join(__dirname, "..", "upload-staging", "problem-solutions");
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

const exams = Object.entries(EXAMS).map(([slug, school]) => {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, slug, "manifest.json"), "utf8"));
  return { slug, school, numbers: manifest.numbers };
});

const examRows = exams.map((exam) => `    (${quote(exam.school)}, ${Math.max(...exam.numbers)}, ${quote(`${YEAR} ${exam.school} ${SUBJECT} ${EXAM_TYPE}`)})`).join(",\n");
const imageRows = exams.flatMap((exam) => exam.numbers.map((number) => `    (${quote(exam.school)}, ${number}, ${quote(`/api/files/problem-solution/${exam.slug}/${String(number).padStart(2, "0")}.webp`)})`)).join(",\n");

process.stdout.write(`-- Generated by scripts/build-hand-solution-sql.cjs. Safe to run more than once.
-- Registers ${exams.length} exams (${YEAR} ${SUBJECT} ${EXAM_TYPE}) and links ${exams.reduce((sum, exam) => sum + exam.numbers.length, 0)} hand-solution images.
-- A problem that already has a video keeps it: only the image (and an empty title) is filled in.
with wanted(school_name, question_count, display_name) as (
  values
${examRows}
),
created as (
  insert into public.school_exam_master
    (exam_year, school_name, subject, exam_type, question_count, scope, display_name, is_active, created_at)
  select ${YEAR}, wanted.school_name, ${quote(SUBJECT)}, ${quote(EXAM_TYPE)}, wanted.question_count, ${quote(SCOPE)}, wanted.display_name, true, now()
  from wanted
  where not exists (
    select 1 from public.school_exam_master existing
    where existing.exam_year = ${YEAR} and existing.school_name = wanted.school_name
      and existing.subject = ${quote(SUBJECT)} and existing.exam_type = ${quote(EXAM_TYPE)}
  )
  returning id, school_name
),
exam as (
  select id, school_name from created
  union all
  select existing.id, existing.school_name from public.school_exam_master existing
  join wanted on wanted.school_name = existing.school_name
  where existing.exam_year = ${YEAR} and existing.subject = ${quote(SUBJECT)} and existing.exam_type = ${quote(EXAM_TYPE)}
),
image(school_name, problem, image_url) as (
  values
${imageRows}
),
saved as (
  insert into public.problem_explanations (content_key, title, image_url, updated_by, updated_at)
  select 'school:' || exam.id || ':' || image.problem, ${quote(TITLE)}, image.image_url, '관리자', now()
  from image join exam on exam.school_name = image.school_name
  on conflict (content_key) do update set
    image_url = excluded.image_url,
    title = case when public.problem_explanations.title = '' then excluded.title else public.problem_explanations.title end,
    updated_by = excluded.updated_by,
    updated_at = excluded.updated_at
  returning content_key
)
select count(*) as linked_problems from saved;
`);
